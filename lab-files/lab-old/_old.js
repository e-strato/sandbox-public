// Лаба «Старые варианты в лабе»: макет страницы лабы, где снятые варианты спрятаны за кнопкой.
// body data-btn — где кнопка: bottom (полоса под списком) · decision (ссылка в «Решено») · header (свитч в шапке) · strip (фишки v1…v20).
// Оси в оболочке (window.LAB): «Порядок» — новые сверху / по порядку; «Старые» — скрыты / показаны. Кнопка на странице переключает ту же ось.
// Пример: лаба на 21 вариант, оставлен v21 (как «Страница новостей»); имена v1–v20 — выдуманы для показа.
(() => {
  const ИМЕНА = ['Лента', 'Карточки', 'Две колонки', 'Три колонки', 'По турнирам', 'По командам', 'Журнал', 'Плитки', 'Таймлайн', 'Крупное фото',
    'Без фото', 'Ранг сбоку', 'Ранг первым', 'Бегущая строка', 'Группы', 'Группы + фильтр', 'Строго', '4 мелких | большая | 2 средние', 'Одна бегущая строка', 'Справа — трансферы', 'Справа — турниры и трансферы']
  const все = ИМЕНА.map((имя, i) => ({ n: i + 1, имя: `v${i + 1} · ${имя}`, h: (i * 47) % 360 }))
  const текущие = все.slice(-1), старые = все.slice(0, -1)
  const btn = document.body.dataset.btn
  let порядок = 'new', показаны = false, открыт = null // открыт — для «фишек»: какая старая версия раскрыта
  const app = document.getElementById('app')

  const карта = (в, старая) => `<div class="card${старая ? ' old' : ''}"><div class="ch"><div class="t"><div class="n">${в.имя}${старая ? '<span class="tag">снят</span>' : '<span class="tag cur">оставлен</span>'}</div>
    <div class="z">${старая ? 'Снят дирижёром — лежит в _отклонено/, виден только по кнопке' : 'Основа — v18, доработки v19–v20'}</div></div><button class="full">⛶ На весь экран</button></div>
    <div class="fr" style="--h:${в.h}"><i></i><i></i><i></i></div></div>`
  const поПорядку = (сп) => порядок === 'new' ? [...сп].reverse() : сп
  const счёт = старые.length
  const подпись = () => показаны ? `Скрыть старые варианты · ${счёт} ▴` : `Показать старые варианты · ${счёт} ▾`

  // Вместе: при «по порядку» старые идут перед оставленным (v1 … v20, v21), при «новые сверху» — после (v21, v20 … v1)
  const списокВместе = () => {
    const старыеHtml = поПорядку(старые).map((в) => карта(в, true)).join('')
    const тек = поПорядку(текущие).map((в) => карта(в, false)).join('')
    if (!показаны) return тек
    const sep = `<div class="sep">Старые · ${счёт}</div>`
    return порядок === 'new' ? тек + sep + старыеHtml : sep + старыеHtml + `<div class="sep">Оставлен</div>` + тек
  }

  const render = () => {
    const шапкаСвитч = btn === 'header' ? `<button class="chip${показаны ? ' on' : ''}" data-t><span class="sw"></span>Старые варианты <span class="cnt">${счёт}</span></button>` : ''
    const вРешено = btn === 'decision' ? `<button class="link" data-t>${подпись()}</button>` : ''
    let низ = ''
    if (btn === 'bottom') низ = `<button class="bar" data-t>${подпись()}</button>`
    let список = списокВместе()
    if (btn === 'strip') {
      список = поПорядку(текущие).map((в) => карта(в, false)).join('')
      const фишки = поПорядку(старые).map((в) => `<button data-v="${в.n}" class="${открыт === в.n ? 'act' : ''}">v${в.n}</button>`).join('')
      const полоса = `<div class="strip"><span class="lb">Старые · ${счёт}</span>${фишки}<button class="all" data-t>${показаны ? 'Скрыть все' : 'Показать все'}</button></div>`
      const раскрыт = открыт && !показаны ? карта(все[открыт - 1], true) : ''
      список = показаны ? списокВместе().replace(`<div class="sep">Старые · ${счёт}</div>`, полоса) : список + полоса + раскрыт
    }
    app.innerHTML = `<div class="pg">
      <div class="hd"><h1>Страница новостей · на решениях виджета</h1><span class="chip">Снять варианты · ZIP</span>
        <span class="chip on"><span class="sw"></span>Экраны во всех вариантах вместе</span>${шапкаСвитч}</div>
      <div class="desc">Страница новостей в стиле виджета v36: строка — заголовок, картинка (если есть), значки…</div>
      <div class="dec"><b>Решено: v21 · Справа — турниры и трансферы</b><p>Страница новостей — в «Страницах» песочницы; дирижёр 30.10: «v18 прям нравится» → доработки v19–v21</p>${вРешено}</div>
      <div class="list">${список}${низ}</div></div>`
  }

  app.addEventListener('click', (e) => {
    const t = e.target.closest('[data-t]'), v = e.target.closest('[data-v]')
    if (t) { показаны = !показаны; открыт = null; render() }
    else if (v) { const n = +v.dataset.v; открыт = открыт === n ? null : n; render() }
  })

  const axes = () => [
    { key: 'order', name: 'Порядок', value: порядок, options: [{ v: 'new', label: 'Новые сверху' }, { v: 'old', label: 'По порядку v1 → v21' }] },
    { key: 'show', name: 'Старые', value: показаны ? 'on' : 'off', options: [{ v: 'off', label: 'Скрыты' }, { v: 'on', label: 'Показаны' }] },
  ]
  const set = (k, v) => { if (k === 'order') порядок = v; else { показаны = v === 'on'; открыт = null } render() }
  const caption = () => порядок === 'new'
    ? 'Новые сверху: оставленный первым, под ним старые от новых к старым (v20 … v1).'
    : 'По порядку: v1, v2 … v20, оставленный v21 — последним, как файлы в папке.'
  window.LAB = { view: 'toolbar', flows: () => [], go: () => {}, cur: () => ({ f: 0, i: 0 }), axes, set, caption }
  render()
})()
